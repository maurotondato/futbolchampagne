export function randomCargada(nombre?: string) {
  const phrase = CARGADAS[Math.floor(Math.random() * CARGADAS.length)];
  if (phrase.includes("{nombre}")) {
    return phrase.replaceAll("{nombre}", nombre?.trim() || "che");
  }
  return phrase;
}

export function randomCargadaExcluding(prev: string, nombre?: string) {
  if (CARGADAS.length <= 1) return randomCargada(nombre);
  let next = randomCargada(nombre);
  let guard = 0;
  while (next === prev && guard < 10) {
    next = randomCargada(nombre);
    guard += 1;
  }
  return next;
}
